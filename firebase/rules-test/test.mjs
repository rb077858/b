await no('wrong code', setDoc(doc(A, 'rm_users/uA'), user({ code: 'zzz' })));
await no('blocked:true on create', setDoc(doc(A, 'rm_users/uA'), user({ blocked: true })));
await no('email mismatch', setDoc(doc(A, 'rm_users/uA'), user({ email: 'evil@x.com' })));
await no('empty first name', setDoc(doc(A, 'rm_users/uA'), user({ first: '' })));
await no('prefilled picks', setDoc(doc(A, 'rm_users/uA'), user({ picks: ['x'] })));
await no('create someone else\'s user doc', setDoc(doc(A, 'rm_users/uOther2'), user()));
await no('not active before signup: read people', getDocs(collection(A, 'rm_people')));
