await no('signup closed', setDoc(doc(env.authenticatedContext('uC', { email: 'c@x.com', email_verified: true }).firestore(), 'rm_users/uC'), user({ email: 'c@x.com', pid: 'pC' })));
await env.withSecurityRulesDisabled(async c => setDoc(doc(c.firestore(), 'rm_public/config'), { open: true }));

console.log('--- אנשים');
const person = (o = {}) => ({ name: 'דני כהן', first: 'דני', last: 'כהן', createdBy: 'uA', createdAt: 1, merged: false, eff: {}, conf: {}, n: 0, effAt: 1, ...o });
