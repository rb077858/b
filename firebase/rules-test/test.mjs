const T = async (name, p) => { try { await p; pass++; console.log('  ok  ', name); } catch (e) { fail++; console.log('  FAIL', name, '\n       ', String(e.message).split('\n')[0]); } };
const ok = (n, p) => T(n, assertSucceeds(p)), no = (n, p) => T(n, assertFails(p));
await env.withSecurityRulesDisabled(async ctx => {
  const db = ctx.firestore();
  await setDoc(doc(db, 'rm_public/config'), { open: true });
  await setDoc(doc(db, 'rm_secret/invite'), { code: 'abc' });
  await setDoc(doc(db, 'rm_users/uBlocked'), { email: 'bl@x.com', first: 'ב', last: 'ל', pid: 'pBl', blocked: true, picks: [], w: {}, code: 'abc' });
  await setDoc(doc(db, 'rm_people/pBl'), { name: 'חסום חסום', merged: false, createdBy: 'uBlocked', eff: {}, conf: {}, n: 0 });
  await setDoc(doc(db, 'rm_people/pOther'), { name: 'אחר אחר', merged: false, createdBy: 'uOther', eff: {}, conf: {}, n: 0 });
  await setDoc(doc(db, 'rm_users/uOther'), { email: 'o@x.com', first: 'אחר', last: 'אחר', pid: 'pOther', blocked: false, picks: [], w: {}, code: 'abc' });
  await setDoc(doc(db, 'rm_claims/pOther_sleep_uOther'), { pid: 'pOther', qid: 'sleep', v: 1, author: 'uOther', self: true, t: 1 });
  await setDoc(doc(db, 'sites/x'), { a: 1 });
});
const anon = env.unauthenticatedContext().firestore();
